// Two products from every subcategory, taken in stable rotation so "New Arrivals"
// always spans the whole catalog rather than just one category.
export const newArrivals = products.filter((_, i) => i % 5 === 0 || i % 5 === 2).slice(0, 16);

// Highest-rated, most-reviewed picks across the catalog.
export const bestsellers = [...products]
  .sort((a, b) => b.rating - a.rating || b.reviewsCount - a.reviewsCount)
  .slice(0, 16);

// Every product carries a launch discount in this catalog, so the Sale page
// surfaces the full discounted range.
export const saleProducts = products.filter((p) => p.discount > 0);

export function getProductById(id) {
  return products.find((p) => p.id === id);
}

export function getRelatedProducts(product, limit = 8) {
  if (!product) return [];
  return products
    .filter((p) => p.id !== product.id && (p.sub === product.sub || p.category === product.category))
    .slice(0, limit);
}
