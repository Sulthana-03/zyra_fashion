// Mints a fresh, one-off welcome code (so the newsletter signup never hands
// out the same code twice in a session) and registers it in `coupons` with
// the same flat ₹50 rule as WELCOME50, so it works immediately at checkout.
export function generateWelcomeCode() {
  const prefixes = ["ZYRA", "STYLE", "FRESH", "WELCOME", "HELLO"];
  let code;
  do {
    const prefix = prefixes[Math.floor(Math.random() * prefixes.length)];
    const num = Math.floor(10 + Math.random() * 90);
    code = `${prefix}${num}`;
  } while (coupons[code]);

  coupons[code] = { flat: 50, minAmount: 500, label: "Flat ₹50 off your first order" };
  return code;
}
